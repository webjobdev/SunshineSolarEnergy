<h2 id="section-1">1. Overview</h2>
<p>At Solor, we stand behind the quality of our products and services. This Refund & Cancellation Policy outlines the terms and conditions for refunds, cancellations, and returns.</p>

<h2 id="section-2">2. Refund Policy</h2>
<h3>Products</h3>
<ul>
    <li><strong>30-Day Money-Back Guarantee:</strong> You may return most products within 30 days of delivery for a full refund.</li>
    <li><strong>Condition:</strong> Products must be returned in their original condition and packaging.</li>
    <li><strong>Restocking Fee:</strong> A 15% restocking fee may apply to certain products.</li>
</ul>

<h3>Services</h3>
<ul>
    <li><strong>Consultations:</strong> Full refund if canceled within 24 hours of booking.</li>
    <li><strong>Installation Services:</strong> Partial refunds may be available based on work completed.</li>
    <li><strong>Maintenance Plans:</strong> Unused portions may be refunded on a pro-rata basis.</li>
</ul>

<h2 id="section-3">3. Cancellation Policy</h2>
<h3>Product Orders</h3>
<ul>
    <li>You may cancel orders within 24 hours of placing them without penalty</li>
    <li>After 24 hours, cancellation fees may apply</li>
    <li>Custom orders cannot be canceled once production has started</li>
</ul>

<h3>Service Appointments</h3>
<ul>
    <li><strong>Free Cancellation:</strong> Cancel at least 48 hours before appointment</li>
    <li><strong>Late Cancellation:</strong> 50% fee for cancellations within 48 hours</li>
    <li><strong>No-Show:</strong> Full charge for missed appointments</li>
</ul>

<h2 id="section-4">4. Return Policy</h2>
<h3>Eligibility for Returns</h3>
<p>To be eligible for a return, items must:</p>
<ul>
    <li>Be returned within 30 days of purchase</li>
    <li>Be in original, unused condition</li>
    <li>Include all original packaging and accessories</li>
    <li>Have proof of purchase</li>
</ul>

<h3>Non-Returnable Items</h3>
<ul>
    <li>Custom-made or personalized products</li>
    <li>Opened or used products</li>
    <li>Products with damaged packaging</li>
    <li>Digital downloads and software</li>
</ul>

<h2 id="section-5">5. Service Cancellations</h2>
<p>For service-related cancellations:</p>
<ul>
    <li><strong>Ongoing Services:</strong> 30 days written notice required for termination</li>
    <li><strong>Maintenance Contracts:</strong> Cancellation fees may apply based on remaining contract term</li>
    <li><strong>Project Work:</strong> Cancellation after commencement will incur charges for work completed</li>
</ul>

<div class="highlight-box">
    <p><strong>Important:</strong> For custom projects, we will provide a detailed cancellation schedule and any applicable fees at the time of contract signing.</p>
</div>

<h2 id="section-6">6. Exceptions</h2>
<p>The following items are not eligible for refund or return:</p>
<ul>
    <li>Gift cards and vouchers</li>
    <li>Clearance or closeout items</li>
    <li>Items damaged by customer misuse</li>
    <li>Products purchased more than 30 days ago</li>
</ul>

<h2 id="section-7">7. How to Request a Refund</h2>
<p>To request a refund or cancellation:</p>
<ol>
    <li>Contact our customer support team at support@domainname.com</li>
    <li>Provide your order number and reason for refund</li>
    <li>Include photos if applicable (for damaged items)</li>
    <li>Wait for our team to review your request</li>
</ol>

<h2 id="section-8">8. Processing Time</h2>
<p>Refund processing timelines:</p>
<ul>
    <li><strong>Approval:</strong> 2-3 business days for review</li>
    <li><strong>Processing:</strong> 5-10 business days after approval</li>
    <li><strong>Credit Card Refunds:</strong> 7-14 business days depending on your bank</li>
    <li><strong>Bank Transfers:</strong> 3-5 business days</li>
</ul>

